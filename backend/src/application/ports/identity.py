from contextlib import AbstractContextManager
from typing import Any, Protocol


class Records(Protocol):
    def one(self, table: str, **filters: Any) -> dict | None: ...
    def many(
        self, table: str, *, limit: int | None = None, offset: int = 0, **filters: Any
    ) -> list[dict]: ...
    def add(self, table: str, **values: Any) -> dict: ...
    def change(self, table: str, record_id: str, **values: Any) -> None: ...
    def remove(self, table: str, record_id: str) -> None: ...


class IdentityStore(Protocol):
    def transaction(
        self, *, write: bool = False
    ) -> AbstractContextManager[Records]: ...


class TokenProvider(Protocol):
    def issue(self, subject: str, session_id: str, kind: str) -> str: ...
    def verify(self, token: str) -> dict: ...


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, encoded: str, password: str) -> bool: ...


class ExternalIdentityProvider(Protocol):
    def verify(self, token: str) -> dict: ...


class MessageCipher(Protocol):
    def encrypt(self, value: str) -> str: ...
    def decrypt(self, value: str) -> str: ...


class Mailer(Protocol):
    def send_reset(self, recipient: str, reset_url: str, message_id: str) -> None: ...
